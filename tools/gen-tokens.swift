#!/usr/bin/env swift
// Generates Folio/Design/Tokens.swift from design/tokens.json.
// Usage (from the repo root): swift tools/gen-tokens.swift
// Re-run whenever the designer refreshes design/tokens.json.

import Foundation

let root = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
let input = root.appendingPathComponent("design/tokens.json")
let output = root.appendingPathComponent("Folio/Design/Tokens.swift")

guard let data = try? Data(contentsOf: input),
      let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else {
    fatalError("Can't read \(input.path). Run from the repo root.")
}

func dict(_ any: Any?) -> [String: Any] { any as? [String: Any] ?? [:] }
func num(_ any: Any?) -> Double? { (any as? NSNumber)?.doubleValue }
func fmt(_ d: Double) -> String {
    d == d.rounded() && abs(d) < 1e9 ? String(Int(d)) : String(d)
}

/// "#RRGGBB" or "rgba(r,g,b,a)" → `RGBA(0xRRGGBB, a)`.
func color(_ any: Any?) -> String? {
    guard let s = any as? String else { return nil }
    if s.hasPrefix("#"), s.count == 7 {
        return "RGBA(0x\(s.dropFirst().uppercased()))"
    }
    if s.hasPrefix("rgba(") {
        let parts = s.dropFirst(5).dropLast().split(separator: ",").map { $0.trimmingCharacters(in: .whitespaces) }
        guard parts.count == 4, let r = Int(parts[0]), let g = Int(parts[1]), let b = Int(parts[2]), let a = Double(parts[3]) else { return nil }
        return "RGBA(0x" + String(format: "%02X%02X%02X", r, g, b) + ", \(fmt(a)))"
    }
    return nil
}

var out = """
// GENERATED by tools/gen-tokens.swift from design/tokens.json. Do not edit by hand.
// Units are points (1 CSS px in the design = 1 pt).

import Foundation

enum Tokens {

"""

// MARK: Themes

let paletteKeys = ["background", "sidebar", "sidebarBorder", "surface", "surfaceSunken", "coverGround",
                   "ink", "ink2", "ink3", "inkOnWash", "rule", "control", "controlSoft", "navActive"]
let themes = dict(json["themes"])
let paper = dict(themes["paper"])
let themeOrder = ["paper", "sage", "mist", "dusk"].filter { themes[$0] != nil }
    + themes.keys.filter { !["paper", "sage", "mist", "dusk"].contains($0) }.sorted()

out += "    // MARK: Themes (keys a theme doesn't state fall back to paper)\n\n"
for name in themeOrder {
    let t = dict(themes[name])
    out += "    static let \(name) = Palette(\n"
    out += "        id: \"\(name)\",\n"
    for key in paletteKeys {
        let value = color(t[key]) ?? color(paper[key]) ?? "RGBA(0x000000)"
        out += "        \(key): \(value),\n"
    }
    let wash = t["wash"] as? String ?? ""
    let washColor = color(wash) ?? color(paper["wash"]) ?? "RGBA(0xF1EADC)"
    let washAsset = wash.hasPrefix("#") ? "nil" : "\"\(wash)\""
    out += "        washColor: \(washColor),\n"
    out += "        washAsset: \(washAsset),\n"
    out += "        washBlend: .\(t["washBlend"] as? String ?? "multiply"),\n"
    out += "        washOpacity: \(fmt(num(t["washOpacity"]) ?? 1)),\n"
    out += "        grainOpacity: \(fmt(num(t["grainOpacity"]) ?? num(paper["grainOpacity"]) ?? 0.9))\n"
    out += "    )\n\n"
}
out += "    static let themes: [Palette] = [\(themeOrder.joined(separator: ", "))]\n\n"

// MARK: Accents

let accents = dict(json["accents"])
let accentOrder = ["ink", "moss", "plum", "graphite"].filter { accents[$0] != nil }
    + accents.keys.filter { !["ink", "moss", "plum", "graphite"].contains($0) }.sorted()
out += "    // MARK: Accents\n\n"
var defaultAccent = accentOrder.first ?? "ink"
for name in accentOrder {
    let a = dict(accents[name])
    if (a["default"] as? Bool) == true { defaultAccent = name }
    let hover = color(a["hover"]).map { "\($0)" } ?? "nil"
    out += "    static let accent\(name.prefix(1).uppercased() + name.dropFirst()) = Accent(id: \"\(name)\", value: \(color(a["value"]) ?? "RGBA(0x000000)"), hover: \(hover))\n"
}
out += "    static let accents: [Accent] = [\(accentOrder.map { "accent" + $0.prefix(1).uppercased() + $0.dropFirst() }.joined(separator: ", "))]\n"
out += "    static let defaultAccentID = \"\(defaultAccent)\"\n\n"

// MARK: Buttons, highlight, shadow

let pb = dict(json["primaryButton"])
out += "    // MARK: Fixed colours\n\n"
out += "    static let primaryButtonBackground = \(color(pb["background"]) ?? "RGBA(0x23201B)")\n"
out += "    static let primaryButtonForeground = \(color(pb["foreground"]) ?? "RGBA(0xF6F1E7)")\n"
out += "    static let highlightFill = \(color(dict(json["highlight"])["fill"]) ?? "RGBA(0x587AA8, 0.24)")\n\n"

// MARK: Type

let type = dict(json["type"])
let families = dict(type["families"])
out += "    // MARK: Type families\n\n"
for role in ["display", "reading", "ui"] {
    let f = dict(families[role])
    let options = (f["options"] as? [String] ?? []).map { "\"\($0)\"" }.joined(separator: ", ")
    out += "    static let \(role)FamilyDefault = \"\(f["default"] as? String ?? "")\"\n"
    out += "    static let \(role)FamilyOptions = [\(options)]\n"
}
out += "\n    // MARK: Type scale\n\n"
let scale = dict(type["scale"])
let scaleOrder = ["wordmarkHero", "screenTitle", "greeting", "editionEnd", "briefTitle", "cardTitle", "wordmark",
                  "readingBody", "briefBody", "quote", "runningHead", "body", "control", "meta", "kicker", "footer"]
let allScale = scaleOrder.filter { scale[$0] != nil } + scale.keys.filter { !scaleOrder.contains($0) }.sorted()
for name in allScale {
    let s = dict(scale[name])
    var args = ["role: .\(s["family"] as? String ?? "ui")", "size: \(fmt(num(s["size"]) ?? 15))"]
    if let lh = num(s["lineHeight"]) { args.append("lineHeight: \(fmt(lh))") }
    if let tr = num(s["tracking"]) { args.append("tracking: \(fmt(tr))") }
    if let w = num(s["weight"]) { args.append("weight: \(fmt(w))") }
    if (s["italic"] as? Bool) == true { args.append("italic: true") }
    if (s["uppercase"] as? Bool) == true { args.append("uppercase: true") }
    if let pg = num(s["paragraphGap"]) { args.append("paragraphGap: \(fmt(pg))") }
    if let c = s["color"] as? String { args.append("color: .\(c)") }
    out += "    static let \(name) = TypeStyle(\(args.joined(separator: ", ")))\n"
}

// MARK: Radius, spacing, reader, window

func numberEnum(_ name: String, _ d: [String: Any]) {
    out += "\n    enum \(name) {\n"
    for key in d.keys.sorted() {
        guard let v = num(d[key]) else { continue }
        out += "        static let \(key): CGFloat = \(fmt(v))\n"
    }
    out += "    }\n"
}
numberEnum("Radius", dict(json["radius"]))
numberEnum("Spacing", dict(json["spacing"]))
numberEnum("Reader", dict(json["reader"]))

let window = dict(json["window"])
let def = window["default"] as? [NSNumber] ?? [1280, 800]
let min = window["min"] as? [NSNumber] ?? [1040, 680]
out += """

    enum Window {
        static let defaultWidth: CGFloat = \(def[0])
        static let defaultHeight: CGFloat = \(def[1])
        static let minWidth: CGFloat = \(min[0])
        static let minHeight: CGFloat = \(min[1])
    }

    enum Watercolor {
        static let files = [\((dict(json["watercolor"])["files"] as? [String] ?? []).map { "\"\($0)\"" }.joined(separator: ", "))]
        static let grainTile: CGFloat = \(fmt(num(dict(dict(json["watercolor"])["grain"])["tile"]) ?? 320))
    }
}

"""

try! out.write(to: output, atomically: true, encoding: .utf8)
print("Wrote \(output.path)")
